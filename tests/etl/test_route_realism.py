"""Route-realism contract regression tests (GDLC Playtest #5 ratchet).

Authored RED before GREEN against data generated by the old synthesis rules:

- ensure_route_degree padded every airport to a min degree floor via
  nearest-neighbour fill — invented routes with no OpenFlights provenance;
- ensure_intl_routes forced every airport to have >=1 direct international
  route, minting nearest-international-airport edges for airports whose real
  route set is all domestic.

Both compensations are removed: routes must follow reality, small airports
keep their real (small) networks (e.g. Takamatsu-class airports with ~5
partners). Only the 20 demo hubs keep a >=8 degree fill, which is the demo
acceptance contract (tests/etl/test_acceptance_demo.py pins it).

RED run: full-mode data from the old pipeline fails these contracts (padded
degrees, invented international edges). GREEN: regeneration after the fix.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "game" / "data"
RAW = ROOT / "etl" / "raw"

WORLD = json.loads((DATA / "world.json").read_text(encoding="utf-8"))

# Original 20 authored demo hubs (same set as tests/etl/test_acceptance_demo.py).
DEMO_IATA = {
    "ATL", "DXB", "DFW", "DEN", "LHR", "ORD", "IST", "LAX", "HND",
    "PVG", "CDG", "AMS", "CAN", "FRA", "PEK", "SIN", "ICN", "HKG",
    "BKK", "MIA",
}


def _roster() -> dict[str, dict]:
    return {a["iata"]: a for a in WORLD["airports"]}


def _generated_undirected() -> set[frozenset[str]]:
    return {frozenset((r["origin"], r["destination"])) for r in WORLD["routes"]}


def _bts_real_pairs() -> set[frozenset[str]]:
    """BTS 2025-03 real-schedule pairs (US-domestic, both in roster, not cancelled).

    Mirrors read_bts_schedule's filter — these real scheduled pairs are merged
    into the route layer by the pipeline (GDLC Playtest #5 data honesty).
    """
    roster = _roster()
    pairs: set[frozenset[str]] = set()
    path = RAW / "bts_on_time_2025_3.csv"
    if not path.exists():
        return pairs
    with path.open(encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            o = (row.get("Origin") or "").strip().upper()
            d = (row.get("Dest") or "").strip().upper()
            if o not in roster or d not in roster or o == d:
                continue
            if roster[o]["country_id"] != "US" or roster[d]["country_id"] != "US":
                continue
            if (row.get("Cancelled") or "").strip() in ("1", "1.00"):
                continue
            pairs.add(frozenset((o, d)))
    return pairs


def _real_undirected() -> set[frozenset[str]]:
    """Undirected sourced pairs: raw OpenFlights routes.dat + BTS 2025-03 real
    schedules, restricted to the roster."""
    iatas = set(_roster())
    pairs: set[frozenset[str]] = set()
    text = (RAW / "routes.dat").read_text(encoding="utf-8", errors="replace")
    for line in text.splitlines():
        f = line.split(",")
        if len(f) >= 6 and f[2] in iatas and f[4] in iatas and f[2] != f[4]:
            pairs.add(frozenset((f[2], f[4])))
    return pairs | _bts_real_pairs()


def test_non_hub_routes_are_real_openflights_edges():
    """Every generated route with no demo-hub endpoint must exist in routes.dat."""
    real = _real_undirected()
    invented = [
        tuple(sorted(e)) for e in _generated_undirected() - real
        if not (e & DEMO_IATA)
    ]
    assert not invented, f"{len(invented)} invented non-hub routes e.g. {invented[:10]}"


def test_no_forced_international_edges():
    """Airports whose real routes are all domestic stay domestic — no nearest-intl minting."""
    roster = _roster()
    real = _real_undirected()
    gen = _generated_undirected()
    violations = []
    for a in roster:
        if a in DEMO_IATA:
            continue
        real_partners = set().union(*(e - {a} for e in real if a in e))
        has_real_intl = any(
            roster[p]["country_id"] != roster[a]["country_id"] for p in real_partners
        )
        if has_real_intl:
            continue
        gen_partners = set().union(*(e - {a} for e in gen if a in e))
        gen_intl = {
            p for p in gen_partners
            if roster[p]["country_id"] != roster[a]["country_id"]
        }
        if gen_intl:
            violations.append((a, sorted(gen_intl)))
    assert not violations, f"invented international routes: {violations[:10]}"


def test_non_hub_degree_matches_real_openflights_degree():
    """Non-hub airports keep exactly their real partner count — no degree-floor fill."""
    roster = _roster()
    real = _real_undirected()
    gen = _generated_undirected()
    padded = []
    for a in roster:
        if a in DEMO_IATA:
            continue
        real_deg = sum(1 for e in real if a in e)
        gen_deg = sum(1 for e in gen if a in e)
        if gen_deg != real_deg:
            padded.append((a, real_deg, gen_deg))
    assert not padded, f"degree padded: {padded[:10]}"


def test_small_airports_stay_small_when_present():
    """Roster airports whose real degree is <5 must not be inflated to a floor."""
    roster = _roster()
    real = _real_undirected()
    gen = _generated_undirected()
    inflated = []
    for a in roster:
        if a in DEMO_IATA:
            continue
        real_deg = sum(1 for e in real if a in e)
        if real_deg >= 5:
            continue
        gen_deg = sum(1 for e in gen if a in e)
        if gen_deg >= 5:
            inflated.append((a, real_deg, gen_deg))
    assert not inflated, f"small airports inflated to >=5: {inflated[:10]}"


def test_every_airport_has_at_least_one_real_route():
    """Selection filter: no roster airport without a real OpenFlights edge (no isolates)."""
    roster = _roster()
    real = _real_undirected()
    isolated = [a for a in roster if not any(a in e for e in real)]
    assert not isolated, f"airports with zero real routes: {isolated[:10]}"


def test_every_flight_pair_is_in_routes():
    """Data honesty (GDLC Playtest #5): every flyable pair must be in the route layer.

    RED: 13,278 BTS 2025-03 real-schedule flights operated on 424 pairs that were
    in neither world.json routes nor routes.dat — the game sold those flights but
    routes/transfers/coverage/challenge systems never saw the pair. Fix: real BTS
    pairs are merged into the routes set at synthesis time.
    """
    import sqlite3

    world_routes = {(r["origin"], r["destination"]) for r in WORLD["routes"]}
    con = sqlite3.connect(ROOT / "etl" / "out" / "flights_2025_03.sqlite")
    try:
        rows = con.execute(
            "SELECT origin_iata, destination_iata, COUNT(*) FROM flight_instance "
            "GROUP BY origin_iata, destination_iata"
        ).fetchall()
    finally:
        con.close()
    off_route = [
        (o, d, n) for o, d, n in rows if (o, d) not in world_routes
    ]
    assert not off_route, (
        f"{sum(n for _, _, n in off_route)} flights on {len(off_route)} pairs "
        f"missing from world.json routes, e.g. {off_route[:6]}"
    )
