export const DICT = { en: EN, zh: ZH };

export function t(locale, key, fallback = key) {
  const table = DICT[locale] || DICT.en;
  return table[key] ?? fallback;
}

/** Template lookup: replaces {name} placeholders in the resolved string. */
export function f(locale, key, vars = {}, fallback) {
  let out = t(locale, key, fallback);
  if (!out) return out;
  Object.keys(vars).forEach((k) => {
    out = out.split(`{${k}}`).join(String(vars[k]));
  });
  return out;
}
