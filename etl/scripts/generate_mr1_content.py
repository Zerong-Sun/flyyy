def generate_city_products(city_info: dict) -> dict:
    """Generate product YAML content for one city."""
    city_id = city_info["city_id"]
    municipality = city_info["municipality"]
    country_id = city_info["country_id"]
    country_zh = city_info.get("country_zh", "")
    city_zh = _get_city_zh(municipality, country_zh)
    rng = city_rng(city_id, "products")

    theme = COUNTRY_PRODUCT_THEMES.get(country_id, COUNTRY_PRODUCT_THEMES["default"])
    categories = list(theme["main"])
    rng.shuffle(categories)
    selected_cats = categories[:5]

    products = []
    for cat in selected_cats:
        product_id = f"{city_id}_{cat}_B"
        params = PRODUCT_PARAMS.get(cat, PRODUCT_PARAMS["食品"])

        # Special case: "化妆品" not in PRODUCT_TEMPLATES keys from run_pipeline, map to closest
        if cat not in PRODUCT_PARAMS and cat == "化妆品":
            params = {"w": (1.0, 3.0), "p": (200.0, 600.0), "sh": (4320, 8760), "fr": 0.2, "rr": (0.3, 0.5),
                      "desc": "化妆品样品合约。"}

        weight = round(rng.uniform(*params["w"]), 1)
        base_price = round(rng.uniform(*params["p"]), 2)
        rarity = round(rng.uniform(*params["rr"]), 2)
        shelf_life = int(rng.randint(*params["sh"]))

        price_mul = theme.get("price_mul", 1.0)
        base_price = round(base_price * price_mul, 2)

        name_zh = f"{city_zh}{cat}合约"

        products.append({
            "product_id": product_id,
            "name_zh": name_zh,
            "category": cat,
            "weight_kg": weight,
            "base_reference_price": base_price,
            "reference_currency": "USD",
            "shelf_life_hours": shelf_life,
            "fragility": params["fr"],
            "rarity": rarity,
            "description": params["desc"],
        })

    return {"products": products}


# ── Main generation logic ─────────────────────────────────────────────

def main():
    import yaml as yaml_lib

    city_list = json.loads(CITY_LIST_PATH.read_text(encoding="utf-8"))

    CITIES_DIR.mkdir(parents=True, exist_ok=True)
    PRODUCTS_DIR.mkdir(parents=True, exist_ok=True)

    generated = 0
    skipped = 0

    for ci in city_list:
        cid = ci["city_id"]

        # Skip 20 authored hub cities
        auth_cities = {"atlanta", "dubai", "dallas", "denver", "london", "chicago", "istanbul",
                       "los_angeles", "tokyo", "shanghai", "paris", "amsterdam", "guangzhou",
                       "frankfurt", "beijing", "singapore", "seoul", "hong_kong", "bangkok", "miami"}
        if cid in auth_cities:
            continue

        # Generate city JSON
        city_content = generate_city_content(ci)
        city_path = CITIES_DIR / f"{cid}.json"
        city_path.write_text(json.dumps(city_content, ensure_ascii=False, indent=2), encoding="utf-8")

        # Generate product YAML
        product_content = generate_city_products(ci)
        product_path = PRODUCTS_DIR / f"{cid}.yaml"

        product_path.write_text(
            yaml_lib.dump(product_content, allow_unicode=True, default_flow_style=False,
                          sort_keys=False, width=120),
            encoding="utf-8",
        )
        generated += 1

    print(f"Generated content for {generated} auto-selected cities (skipped {skipped} authored)")
    print(f"  City JSON files: {CITIES_DIR}")
    print(f"  Product YAML files: {PRODUCTS_DIR}")

    # Quick sample check
    sample_cid = city_list[0]["city_id"]
    sample_city = json.loads((CITIES_DIR / f"{sample_cid}.json").read_text(encoding="utf-8"))
    print(f"\nSample city [{sample_cid}]:")
    print(f"  short: {sample_city['short_description'][:80]}...")
    print(f"  overview: {sample_city['overview'][:80]}...")


if __name__ == "__main__":
    main()
