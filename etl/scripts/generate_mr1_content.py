def _get_elements(country_id: str) -> dict:
    """Get country-specific elements, resolving duplicate keys."""
    # Some countries appear multiple times in _COUNTRY; take the last (most complete) definition
    elements = _COUNTRY.get(country_id, _COUNTRY["default"])
    if len(elements) < 5:  # likely a placeholder
        elements = _COUNTRY["default"]
    return elements


def _format_field(template: str, elements: dict, city_name: str, country_name: str, rng: random.Random) -> str:
    """Format a template string with random element choices and {city}/{country} substitution."""
    result = template
    result = result.replace("{city}", city_name)
    result = result.replace("{country}", country_name)

    # Pick from list values
    for key in ["imp", "feat", "angle", "location", "ov_imp", "loc", "ov_feat", "ov_trade",
                "hist", "geo", "econ", "food", "airport", "tip"]:
        placeholder = "{" + key + "}"
        if placeholder in result:
            val = elements.get(key, f"[{key}]")
            if isinstance(val, list):
                val = rng.choice(val)
            elif val is None or val == "":
                val = f"[{key}]"
            result = result.replace(placeholder, val)

    return result


